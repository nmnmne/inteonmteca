"""Rebuild the transparent handwritten vector (no raster payloads).

Run: python scripts/vectorize-handwriting.py
Build-only dependencies: Pillow, vtracer==0.6.15.
The original PNGs are retained; the site only consumes the generated SVG.
Two binary spline traces preserve the hand's irregular outline and lime ink.
A small repeating vector mask adds dry-print pores without runtime filters.
"""
from io import BytesIO
from pathlib import Path
import xml.etree.ElementTree as ET

from PIL import Image
import vtracer

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets/logo-handwriting.png'
OUTPUT = ROOT / 'assets/logo-handwriting.svg'


def trace(image, predicate):
    bitmap = Image.new('RGB', image.size, 'white')
    pixels = image.get_flattened_data() if hasattr(image, 'get_flattened_data') else image.getdata()
    bitmap.putdata([(0, 0, 0) if predicate(*pixel) else (255, 255, 255)
                    for pixel in pixels])
    buffer = BytesIO()
    bitmap.save(buffer, format='PNG')
    svg = vtracer.convert_raw_image_to_svg(
        buffer.getvalue(), img_format='png', colormode='binary', mode='spline',
        filter_speckle=2, corner_threshold=65, length_threshold=3.5,
        max_iterations=10, splice_threshold=45, path_precision=2)
    paths = []
    for element in ET.fromstring(svg):
        if element.tag.endswith('path'):
            transform = element.get('transform')
            attrs = f' transform="{transform}"' if transform else ''
            paths.append(f'<path d="{element.attrib["d"]}"{attrs}/>')
    return '\n'.join(paths)


def build():
    image = Image.open(SOURCE).convert('RGBA')
    width, height = image.size
    silhouette = trace(image, lambda r, g, b, a: a >= 100)
    lime = trace(image, lambda r, g, b, a: a >= 110 and g > r * 1.12 and g > b * 1.18)
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" fill-rule="evenodd">
<title>inteonmteca — handwritten ink</title>
<!-- Generated by scripts/vectorize-handwriting.py; transparent, vector-only. -->
<defs>
  <pattern id="dry-ink" width="37" height="29" patternUnits="userSpaceOnUse">
    <rect width="37" height="29" fill="white"/>
    <g fill="black" opacity=".16">
      <ellipse cx="3.7" cy="7.2" rx=".65" ry=".28"/>
      <ellipse cx="19.2" cy="21.3" rx=".38" ry=".6"/>
      <circle cx="30.8" cy="11.6" r=".38"/>
    </g>
    <path d="M10 16l2.4-.5M25 3l1.5.3M31 25l2-.4" stroke="black" stroke-width=".35" opacity=".12"/>
  </pattern>
  <mask id="ink-wear" maskUnits="userSpaceOnUse" x="0" y="0" width="{width}" height="{height}" style="mask-type:luminance">
    <rect width="{width}" height="{height}" fill="url(#dry-ink)"/>
  </mask>
</defs>
<g mask="url(#ink-wear)">
<g fill="#f4f4ed">
{silhouette}
</g>
<g fill="#b8ed79" opacity=".82">
{lime}
</g>
</g>
</svg>
'''


if __name__ == '__main__':
    result = build()
    OUTPUT.write_text(result, encoding='utf-8', newline='\n')
    print(f'{OUTPUT}: {len(result.encode("utf-8"))} bytes, {result.count("<path")} paths')
